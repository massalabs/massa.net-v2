const byLocale: Partial<Record<LocaleCode, Record<string, string>>> = {
  en,
  fr,
}

export function hasStaticDictionary(locale: LocaleCode): boolean {
  return byLocale[locale] != null
}

export function getEnglishMessage(key: string): string {
  return en[key] ?? key
}

export function getMessage(locale: LocaleCode, key: string): string {
  const fromLocale = byLocale[locale]?.[key]
  if (fromLocale != null && fromLocale !== '') return fromLocale
  const fromEn = en[key]
  if (fromEn != null) return fromEn
  return key
}

export function interpolate(template: string, vars?: Record<string, string | number>): string {
  if (!vars) return template
  let out = template
  for (const [k, v] of Object.entries(vars)) {
    out = out.split(`{{${k}}}`).join(String(v))
  }
  return out
}
